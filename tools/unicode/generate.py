def esc(points):
    result=''
    for cp in points:
        if cp>65535:
            cp-=65536
            result+='\\u%04x\\u%04x'%(0xd800+(cp>>10),0xdc00+(cp&1023))
        else: result+='\\u%04x'%cp
    return result
